class StarterLandingPageView(APIView):
    """GET /api/v1/training/starter-page/

    Public read-only endpoint returning the PUBLISHED section payload for
    the Starter campaign landing page. Draft data, revisions and staff
    metadata are never exposed here. Falls back to the compiled default
    sections when no page row exists so the public page never breaks.
    """

    permission_classes = [AllowAny]

    def get(self, request):
        from .landing_sections import default_sections
        page = StarterLandingPage.objects.filter(slug=StarterLandingPage.SLUG).first()
        sections = page.published_sections if page and page.published_sections else default_sections()
        return Response({'sections': sections})


class StarterLandingPagePreviewView(APIView):
    """GET /api/v1/training/starter-page/preview/?token=<signed_token>

    Returns the DRAFT section payload when a valid CMS-generated preview
    token is supplied. Tokens are short-lived, signed, and bound to the
    starter landing slug (see preview_service). Used only by the shared
    renderer in preview mode — submission stays inert on the client.
    """

    permission_classes = [AllowAny]

    def get(self, request):
        from .landing_sections import default_sections
        from .preview_service import is_preview_token_valid

        token = request.query_params.get('token', '').strip()
        if not token or not is_preview_token_valid(token, StarterLandingPage.SLUG):
            return Response({'detail': 'Invalid or expired preview token.'}, status=403)

        page = StarterLandingPage.objects.filter(slug=StarterLandingPage.SLUG).first()
        sections = page.draft_sections if page and page.draft_sections else default_sections()
        return Response({'sections': sections, 'preview': True})
